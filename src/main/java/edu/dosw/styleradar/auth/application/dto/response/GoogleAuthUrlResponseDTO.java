package edu.dosw.styleradar.auth.application.dto.response;

import io.swagger.v3.oas.annotations.media.Schema;

@Schema(description = "Google OAuth2 authorization URL with the anti-CSRF state generated by ms-auth")
public record GoogleAuthUrlResponseDTO(
        @Schema(
                description = "Full Google Accounts URL to redirect the user for OIDC consent",
                example = "https://accounts.google.com/o/oauth2/v2/auth?client_id=xxx.apps.googleusercontent.com&redirect_uri=http%3A%2F%2Flocalhost%3A8100%2Fapi%2Fv1%2Fauth%2Foauth2%2Fgoogle%2Fcallback&response_type=code&scope=openid%20email%20profile&state=abc")
        String authorizationUrl,
        @Schema(
                description = "Random single-use cryptographic state of the OAuth2 flow",
                example = "anti-csrf-state-12345")
        String state,
        @Schema(
                description = "Lifetime in seconds of the state in Redis",
                example = "300")
        long expiresInSeconds,
        @Schema(
                description = "Effective redirect URI included in the authorization URL",
                example = "http://localhost:8100/api/v1/auth/oauth2/google/callback")
        String redirectUri) {
}

